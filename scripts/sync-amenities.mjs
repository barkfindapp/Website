// Copies the app's amenity definitions (codes, labels, tooltips, which categories they apply
// to) into api/_lib/amenities.ts for HQ. The app repo is the source of truth; run this again
// whenever src/lib/locationTypeData.ts changes there:
//   node scripts/sync-amenities.mjs [path-to-barkfind-app-v1]
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const appRoot = path.resolve(process.argv[2] || path.join(process.cwd(), '..', 'barkfind-app-v1'));
const file = path.join(appRoot, 'src/lib/locationTypeData.ts');
const src = fs.readFileSync(file, 'utf8');
let commit = 'unknown';
try { commit = execSync('git log -1 --format=%h -- src/lib/locationTypeData.ts', { cwd: appRoot }).toString().trim(); } catch { /* not a git checkout */ }

// The app's own label casing (src/lib/labels.ts sentenceCaseLabel), so HQ shows the same words.
const ACRONYMS = new Set(['uk', 'bbq', 'wc', 'atm', 'ev', 'tv', 'wifi']);
const normaliseWord = (w) => w.split('-').map((p) => (ACRONYMS.has(p.toLowerCase()) ? p.toUpperCase() : p.toLowerCase())).join('-');
function sentenceCaseLabel(input) {
  const raw = (input || '').trim(); if (!raw) return '';
  const isSlug = !/\s/.test(raw) && raw === raw.toLowerCase() && /[-_]/.test(raw);
  const words = (isSlug ? raw.replace(/[-_]+/g, ' ') : raw).split(/\s+/).filter(Boolean).map(normaliseWord);
  const first = words[0];
  return [ACRONYMS.has(first.toLowerCase()) ? first : first.charAt(0).toUpperCase() + first.slice(1), ...words.slice(1)].join(' ');
}

// typeToGroup: category -> group
const ttg = /const typeToGroup[^=]*=\s*\{([\s\S]*?)\};/.exec(src);
if (!ttg) throw new Error('typeToGroup not found');
const typeToGroup = {};
for (const m of ttg[1].matchAll(/"?([a-z-]+)"?\s*:\s*"([a-z-]+)"/g)) typeToGroup[m[1]] = m[2];
// group -> the const holding its amenities (from getAmenitiesForGroup)
const gfg = /function getAmenitiesForGroup[\s\S]*?\{([\s\S]*?)\n\}/.exec(src);
const groupConst = {};
for (const m of gfg[1].matchAll(/case "([a-z-]+)":\s*return (\w+);/g)) groupConst[m[1]] = m[2];
const groups = {};
for (const [group, name] of Object.entries(groupConst)) {
  const block = new RegExp(`const ${name}: AmenityCategoryData\\[\\] = \\[([\\s\\S]*?)\\n\\];`).exec(src);
  if (!block) throw new Error('amenities for ' + name + ' not found');
  groups[group] = [];
  for (const sec of block[1].matchAll(/title:\s*"([^"]+)",\s*items:\s*\[([\s\S]*?)\]/g)) {
    const items = [...sec[2].matchAll(/\{\s*id:\s*"([^"]+)",\s*label:\s*"([^"]+)"(?:,\s*tooltip:\s*"([^"]*)")?\s*\}/g)]
      .map((x) => ({ code: x[1], label: sentenceCaseLabel(x[2]), tooltip: x[3] || '' }));
    groups[group].push({ title: sec[1], items });
  }
}
const codes = Object.values(groups).flat().flatMap((s) => s.items.map((i) => i.code));
if (codes.length < 20 || new Set(codes).size !== codes.length) throw new Error('unexpected amenity list: ' + codes.length + ' codes');
const out = `// GENERATED by scripts/sync-amenities.mjs from barkfind-app-v1 src/lib/locationTypeData.ts
// (app commit ${commit}). Do not edit by hand: change the app, then run the script again.
export const AMENITY_SOURCE = ${JSON.stringify({ file: 'barkfind-app-v1/src/lib/locationTypeData.ts', commit })};
export const CATEGORY_GROUP: Record<string, string> = ${JSON.stringify(typeToGroup, null, 2)};
export const AMENITY_GROUPS: Record<string, { title: string; items: { code: string; label: string; tooltip: string }[] }[]> = ${JSON.stringify(groups, null, 2)};
export const AMENITY_CODES: readonly string[] = ${JSON.stringify(codes)};
`;
fs.writeFileSync(path.join(process.cwd(), 'api/_lib/amenities.ts'), out);
console.log(`wrote api/_lib/amenities.ts: ${codes.length} codes in ${Object.keys(groups).length} groups, ${Object.keys(typeToGroup).length} categories, app commit ${commit}`);
